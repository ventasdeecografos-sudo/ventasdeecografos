create table if not exists public.quote_requests (
  id bigint generated by default as identity primary key,
  customer_name text not null check (length(trim(customer_name)) between 2 and 120),
  customer_email text not null check (length(customer_email) <= 254),
  customer_phone text not null check (customer_phone ~ '^\+[1-9][0-9]{7,14}$'),
  quote_items jsonb not null check (jsonb_typeof(quote_items) = 'array'),
  subtotal bigint not null check (subtotal >= 0),
  discount_percent numeric(5, 2) not null check (discount_percent between 0 and 100),
  discount_amount bigint not null check (discount_amount >= 0),
  tax_amount bigint not null check (tax_amount >= 0),
  total bigint not null check (total >= 0),
  unpriced_items integer not null check (unpriced_items >= 0),
  contact_verified boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.quote_requests enable row level security;

revoke all on public.quote_requests from public, anon, authenticated;
grant all on public.quote_requests to service_role;
grant usage, select on sequence public.quote_requests_id_seq to service_role;
